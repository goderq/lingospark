const choice = (
  speaker,
  line,
  prompt,
  answer,
  wrong,
  explanation,
  consequence,
) => ({
  type: "choice",
  speaker,
  line,
  prompt,
  answer,
  options: [answer, ...wrong],
  explanation,
  consequence,
});

const input = (speaker, line, prompt, answer, answers, hint, explanation) => ({
  type: "input",
  speaker,
  line,
  prompt,
  answer,
  answers: [answer, ...(answers || [])],
  hint,
  explanation,
});

