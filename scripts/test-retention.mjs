import assert from 'node:assert/strict';
import { lessons } from '../src/data/course.js';
import { DAY, enrollRetention, retentionDeck, retentionSummary, finishRetention } from '../src/utils/retention.js';

const now = Date.UTC(2026, 10, 15, 12);
const lesson = lessons[0];
const original = { completed: [lesson.id], retention: {}, totalXP: 40 };
const progress = { ...original, retention: enrollRetention(original.completed, {}, now) };
const token = progress.retention[lesson.id].dueAt;
assert.equal(token, now + DAY);
assert.equal(retentionSummary(progress, lessons, now).due.length, 0);
assert.equal(retentionSummary(progress, lessons, token).due[0].id, lesson.id);
assert.equal(enrollRetention(progress.completed, progress.retention, now + DAY), progress.retention, 'restoring/reopening must not restart a timer');
const deck = retentionDeck(lesson, () => 0.37);
const answers = deck.map(e => ({ id: e.id, input: e.answer }));
assert.equal(finishRetention(progress, lessons, lesson.id, token, answers, now), progress, 'cannot check before the interval');
assert.equal(finishRetention(progress, lessons, lesson.id, token, answers.slice(1), token), progress, 'partial tests must not count');
assert.equal(finishRetention(progress, lessons, lesson.id, token, answers.map(() => answers[0]), token), progress, 'duplicate answers must not count');
const first = finishRetention(progress, lessons, lesson.id, token, answers, token);
assert.equal(first.retention[lesson.id].successfulChecks, 1);
assert.equal(first.retention[lesson.id].verifiedAt, null);
assert.equal(first.retention[lesson.id].dueAt, token + 3 * DAY);
assert.equal(finishRetention(first, lessons, lesson.id, token, answers, token), first, 'a repeated submit must not count');
const secondDue = first.retention[lesson.id].dueAt;
const second = finishRetention(first, lessons, lesson.id, secondDue, answers, secondDue);
assert.equal(second.retention[lesson.id].verifiedAt, secondDue);
assert.equal(second.retention[lesson.id].dueAt, secondDue + 7 * DAY);
assert.equal(second.totalXP, original.totalXP, 'retention must not award lesson XP again');
assert.deepEqual(second.completed, original.completed, 'retention must not unlock courses');
assert.equal(retentionSummary(second, lessons, secondDue).verified, 1);
const failedAnswers = deck.map(e => ({ id: e.id, input: e.options.find(option => option !== e.answer) }));
const thirdDue = second.retention[lesson.id].dueAt;
const failed = finishRetention(second, lessons, lesson.id, thirdDue, failedAnswers, thirdDue);
assert.equal(failed.retention[lesson.id].successfulChecks, 0);
assert.equal(failed.retention[lesson.id].verifiedAt, null);
assert.equal(failed.retention[lesson.id].dueAt, thirdDue + DAY);
assert.equal(finishRetention({ ...progress, completed: [] }, lessons, lesson.id, token, answers, token).retention, progress.retention);
assert.equal(finishRetention(progress, lessons, 'missing', token, answers, token), progress);
assert.deepEqual(JSON.parse(JSON.stringify(second)), second, 'backup/cloud JSON round trip must preserve retention');
assert.equal(enrollRetention([lesson.id], null, now)[lesson.id].verifiedAt, null, 'old saves without schedules must not imply mastery');
const sampleLesson = { id: 'threshold', exercises: Array.from({ length: 5 }, (_, i) => ({ id: `t${i}`, type: 'choice', answer: 'Yes', options: ['Yes', 'No'] })) };
const sampleProgress = { completed: ['threshold'], retention: enrollRetention(['threshold'], {}, now) };
const thresholdAnswers = sampleLesson.exercises.map((e, i) => ({ id: e.id, input: i === 0 ? 'No' : 'Yes' }));
assert.equal(finishRetention(sampleProgress, [sampleLesson], 'threshold', token, thresholdAnswers, token).retention.threshold.successfulChecks, 1, '80 percent must pass');
thresholdAnswers[1].input = 'No';
assert.equal(finishRetention(sampleProgress, [sampleLesson], 'threshold', token, thresholdAnswers, token).retention.threshold.successfulChecks, 0, '60 percent must fail');
assert.equal(finishRetention(progress, lessons, lesson.id, token, answers.map(() => null), token), progress, 'malformed answers must be ignored');
for (const item of lessons) {
  const originalOptions = JSON.stringify(item.exercises);
  const sample = retentionDeck(item);
  assert.ok(sample.length > 0, `${item.id} needs checkable questions`);
  assert.equal(new Set(sample.map(e => e.id)).size, sample.length);
  assert.equal(sample.length, Math.min(5, item.exercises.filter(e => e.type === 'choice').length));
  for (const exercise of sample) assert.ok(exercise.options.includes(exercise.answer));
  assert.equal(JSON.stringify(item.exercises), originalOptions, 'shuffling must not mutate the course');
}
console.log(`retention: delayed checks, restore, failures, duplicate submits and ${lessons.length} lesson decks passed`);
